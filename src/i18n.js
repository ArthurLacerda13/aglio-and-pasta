export function getCurrentLang() {
  const saved = localStorage.getItem('aglio_lang');
  if (saved && ['pt', 'en', 'it'].includes(saved)) {
    return saved;
  }
  // Auto detect or default to PT
  const browserLang = (navigator.language || '').toLowerCase();
  if (browserLang.startsWith('it')) return 'it';
  if (browserLang.startsWith('pt')) return 'pt';
  return 'pt'; // Default to PT for this project
}

export function setLanguage(lang) {
  if (!translations[lang]) return;
  localStorage.setItem('aglio_lang', lang);
  applyTranslations(lang);
  updateActiveLanguageUI(lang);
}

export function applyTranslations(lang = getCurrentLang()) {
  const dict = translations[lang] || translations.pt;
  
  // Elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.setAttribute('placeholder', dict[key]);
      } else {
        el.innerHTML = dict[key];
      }
    }
  });

  // Elements with data-i18n-placeholder attribute
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Update HTML lang attribute
  document.documentElement.lang = lang;
}

export function updateActiveLanguageUI(lang = getCurrentLang()) {
  const flags = { pt: '🇧🇷 PT', en: '🇺🇸 EN', it: '🇮🇹 IT' };
  
  // Update desktop selector display
  const currentLangLabel = document.getElementById('current-lang-label');
  if (currentLangLabel) {
    currentLangLabel.textContent = flags[lang] || lang.toUpperCase();
  }

  // Update active state on options
  document.querySelectorAll('.lang-option').forEach(btn => {
    const targetLang = btn.getAttribute('data-lang');
    if (targetLang === lang) {
      btn.classList.add('active-lang', 'text-amber-400', 'font-bold');
      btn.classList.remove('text-gray-300', 'text-gray-600');
    } else {
      btn.classList.remove('active-lang', 'text-amber-400', 'font-bold');
      btn.classList.add('text-gray-300');
    }
  });
}

export function initI18n() {
  const currentLang = getCurrentLang();
  applyTranslations(currentLang);
  updateActiveLanguageUI(currentLang);

  // Setup click listeners for language buttons
  document.querySelectorAll('.lang-option').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const newLang = btn.getAttribute('data-lang');
      if (newLang) {
        setLanguage(newLang);
        // Dispatch custom event if other modules need to react
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: newLang } }));
      }
    });
  });
}
